//go:embed bootstrap/*
var bootstrap embed.FS

// Generate replaces the dynamic RegisterFunc adapters in a freshly staged Bao
// package, emits fixed-signature stubs and bundles its licensed runtime support.
func Generate(out, pkg, target string, m Manifest, symbols []string) error {
	if err := m.Validate(); err != nil {
		return err
	}
	parts := strings.Split(target, "/")
	if len(parts) != 2 {
		return fmt.Errorf("invalid target")
	}
	arch := parts[1]
	goPath := filepath.Join(out, "symbols_"+parts[0]+"_"+arch+".go")
	source, err := os.ReadFile(goPath)
	if err != nil {
		return err
	}
	sum := sha256.Sum256(source)
	namespace := fmt.Sprintf("bao_fixed_%x_", sum[:6])
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, goPath, source, parser.ParseComments)
	if err != nil {
		return err
	}
	var generated, assembly strings.Builder
	constraint := parts[0] + " && " + arch
	fmt.Fprintf(&generated, "// Code generated by Bao from fixed C signatures; DO NOT EDIT.\n//go:build %s\n\npackage %s\n\nimport (\"math\";\"runtime\";\"unsafe\")\n\nvar _ = math.Float64bits\n//go:linkname baoCgocall runtime.cgocall\nfunc baoCgocall(fn,frame unsafe.Pointer) int32\ntype baoCallFrame struct { fn uintptr; result uint64; args [32]uint64 }\n", constraint, pkg)
	assembly.WriteString("// Code generated by Bao. C ABI entries run through runtime.cgocall.\n#include \"textflag.h\"\n")
	count := 0
	emit := func(f Function, address string, factory bool) (string, error) {
		index := count
		count++
		entry := fmt.Sprintf("baoEntry%d", index)
		native := fmt.Sprintf("%scall_%d", namespace, index)
		asm, err := callAssembly(target, native, f)
		if err != nil {
			return "", err
		}
		assembly.WriteString(accessor(arch, entry, native))
		assembly.WriteString(asm)
		fmt.Fprintf(&generated, "\nfunc %s() uintptr\n", entry)
		var params, args []string
		for i, t := range f.Params {
			params = append(params, fmt.Sprintf("a%d %s", i, GoType(t)))
			args = append(args, GoType(t))
		}
		result := GoType(f.Result)
		ret := ""
		if result != "" {
			ret = " " + result
		}
		name := f.Name
		if factory {
			name = fmt.Sprintf("baoBind%d", index)
			fmt.Fprintf(&generated, "func %s(address uintptr) func(%s)%s { return func(%s)%s {\n", name, strings.Join(args, ","), ret, strings.Join(params, ","), ret)
		} else {
			fmt.Fprintf(&generated, "func %s(%s)%s {\n address := %s\n", name, strings.Join(params, ","), ret, address)
		}
		hasPointers := false
		for _, t := range f.Params {
			hasPointers = hasPointers || t == "pointer"
		}
		if hasPointers {
			generated.WriteString(" var pin runtime.Pinner\n defer pin.Unpin()\n")
			for i, t := range f.Params {
				if t == "pointer" {
					fmt.Fprintf(&generated, " pin.Pin(a%d)\n", i)
				}
			}
		}
		generated.WriteString(" f := baoCallFrame{fn:address}\n")
		for i, t := range f.Params {
			value := fmt.Sprintf("uint64(a%d)", i)
			switch t {
			case "pointer":
				value = fmt.Sprintf("uint64(uintptr(a%d))", i)
			case "float32":
				value = fmt.Sprintf("uint64(math.Float32bits(a%d))", i)
			case "float64":
				value = fmt.Sprintf("math.Float64bits(a%d)", i)
			}
			fmt.Fprintf(&generated, " f.args[%d] = %s\n", i, value)
		}
		fmt.Fprintf(&generated, " baoCgocall(unsafe.Pointer(%s()), unsafe.Pointer(&f))\n runtime.KeepAlive(&f)\n", entry)
		for i, t := range f.Params {
			if t == "pointer" {
				fmt.Fprintf(&generated, " runtime.KeepAlive(a%d)\n", i)
			}
		}
		switch f.Result {
		case "", "void":
		case "pointer":
			generated.WriteString(" return *(*unsafe.Pointer)(unsafe.Pointer(&f.result))\n")
		case "float32":
			generated.WriteString(" return math.Float32frombits(uint32(f.result))\n")
		case "float64":
			generated.WriteString(" return math.Float64frombits(f.result)\n")
		default:
			fmt.Fprintf(&generated, " return %s(f.result)\n", result)
		}
		generated.WriteString("}\n")
		if factory {
			generated.WriteString("}\n")
		}
		return name, nil
	}
	// Record function variable declarations, including the generated init locals.
	types := map[string]*ast.FuncType{}
	ast.Inspect(file, func(n ast.Node) bool {
		if v, ok := n.(*ast.ValueSpec); ok {
			if t, ok := v.Type.(*ast.FuncType); ok {
				for _, name := range v.Names {
					types[name.Name] = t
				}
			}
		}
		return true
	})
	var generationErr error
	ast.Inspect(file, func(n ast.Node) bool {
		block, ok := n.(*ast.BlockStmt)
		if !ok {
			return true
		}
		for i, stmt := range block.List {
			expr, ok := stmt.(*ast.ExprStmt)
			if !ok {
				continue
			}
			call, ok := expr.X.(*ast.CallExpr)
			if !ok {
				continue
			}
			sel, ok := call.Fun.(*ast.SelectorExpr)
			if !ok {
				continue
			}
			x, ok := sel.X.(*ast.Ident)
			if !ok || x.Name != "purego" || sel.Sel.Name != "RegisterFunc" {
				continue
			}
			if len(call.Args) != 2 {
				generationErr = fmt.Errorf("unexpected runtime adapter")
				continue
			}
			ptr, ok := call.Args[0].(*ast.UnaryExpr)
			if !ok {
				generationErr = fmt.Errorf("unexpected function registration")
				continue
			}
			name, ok := ptr.X.(*ast.Ident)
			if !ok {
				generationErr = fmt.Errorf("unexpected registration target")
				continue
			}
			t, ok := types[name.Name]
			if !ok {
				generationErr = fmt.Errorf("missing generated runtime signature for %s", name.Name)
				continue
			}
			f, err := fromFuncType(t)
			if err != nil {
				generationErr = err
				continue
			}
			factory, err := emit(f, "", true)
			if err != nil {
				generationErr = err
				continue
			}
			block.List[i] = &ast.AssignStmt{Lhs: []ast.Expr{name}, Tok: token.ASSIGN, Rhs: []ast.Expr{&ast.CallExpr{Fun: ast.NewIdent(factory), Args: []ast.Expr{call.Args[1]}}}}
		}
		return true
	})
	if generationErr != nil {
		return generationErr
	}
	// Linux resolves imports through dlsym, itself called using a fixed adapter.
	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FuncDecl)
		if !ok || fn.Name.Name != "lookup" {
			continue
		}
		factory, err := emit(Function{Params: []string{"uintptr", "pointer"}, Result: "uintptr"}, "", true)
		if err != nil {
			return err
		}
		generated.WriteString("\n//go:cgo_import_dynamic bao_dlsym dlsym \"libdl.so.2\"\nfunc baoDlsymAddress() uintptr\n")
		// Use a real native tail bridge so function-address resolution has the
		// same semantics on all Linux ELF targets, including PPC64 ELFv2.
		native := namespace + "dlsym"
		assembly.WriteString(accessor(arch, "baoDlsymAddress", native))
		fmt.Fprintf(&assembly, "\nTEXT %s(SB),NOSPLIT|NOFRAME,$0-0\n JMP bao_dlsym(SB)\n", native)
		body, err := parser.ParseFile(token.NewFileSet(), "lookup.go", "package x\nfunc lookup(name string) uintptr { b:=append([]byte(name),0); call:="+factory+"(baoDlsymAddress()); p:=call(0,unsafe.Pointer(&b[0])); runtime.KeepAlive(b); if p==0 {panic(\"native symbol unavailable: \"+name)}; return p }", 0)
		if err != nil {
			return err
		}
		fn.Body = body.Decls[0].(*ast.FuncDecl).Body
	}
	// Remove the purego import; imports required by the generated lookup stay in
	// this source file, while frame/marshaling imports live in bindings.go.
	for _, decl := range file.Decls {
		if d, ok := decl.(*ast.GenDecl); ok && d.Tok == token.IMPORT {
			var specs []ast.Spec
			hasUnsafe := false
			for _, sp := range d.Specs {
				im := sp.(*ast.ImportSpec)
				if im.Path.Value == strconv.Quote("github.com/ebitengine/purego") {
					continue
				}
				hasUnsafe = hasUnsafe || im.Path.Value == `"unsafe"`
				specs = append(specs, sp)
			}
			if parts[0] == "linux" && !hasUnsafe {
				specs = append(specs, &ast.ImportSpec{Path: &ast.BasicLit{Kind: token.STRING, Value: `"unsafe"`}})
			}
			d.Specs = specs
		}
	}
	for _, f := range m.Functions {
		index := -1
		for i, s := range symbols {
			if f.Symbol == s {
				index = i
				break
			}
		}
		if index < 0 {
			return fmt.Errorf("binding %s has no symbol accessor", f.Name)
		}
		if _, err := emit(f, fmt.Sprintf("SymbolAddr%d()", index), false); err != nil {
			return err
		}
	}
	var rewritten bytes.Buffer
	if err = format.Node(&rewritten, fset, file); err != nil {
		return err
	}
	if bytes.Contains(rewritten.Bytes(), []byte("purego.")) {
		return fmt.Errorf("unhandled dynamic runtime adapter")
	}
	if err = os.WriteFile(goPath, rewritten.Bytes(), 0644); err != nil {
		return err
	}
	b, err := format.Source([]byte(generated.String()))
	if err != nil {
		return fmt.Errorf("generated typed Go: %w\n%s", err, generated.String())
	}
	if err = os.WriteFile(filepath.Join(out, "bindings_"+parts[0]+"_"+arch+".go"), b, 0644); err != nil {
		return err
	}
	if err = os.WriteFile(filepath.Join(out, "bindings_"+parts[0]+"_"+arch+".s"), []byte(assembly.String()), 0644); err != nil {
		return err
	}
	if parts[0] != "windows" {
		err = emitBootstrap(out, pkg, parts[0], arch)
	}
	if err != nil {
		return err
	}
	b, err = json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	if err = os.WriteFile(filepath.Join(out, "bao-signatures.json"), append(b, '\n'), 0644); err != nil {
		return err
	}
	metadata := struct {
		Manifest Manifest `json:"signature_manifest"`
		Mode     string   `json:"mode"`
		Runtime  string   `json:"runtime"`
	}{m, "generated fixed-signature assembly; no consumer purego module", "adapted bundled purego v0.11.3 fakecgo bootstrap; Apache-2.0/BSD-3-Clause"}
	if parts[0] == "darwin" || parts[0] == "linux" {
		metadata.Runtime = "adapted bundled purego v0.11.3 fakecgo bootstrap, installed from runtime._cgo_init unless runtime/cgo is linked"
	}
	if parts[0] == "windows" {
		metadata.Runtime = "stock Go Windows runtime.cgocall; original fixed ABI adapters; no fakecgo bootstrap"
	}
	b, err = json.MarshalIndent(metadata, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(out, "bao-bindings.json"), append(b, '\n'), 0644)
}

func fromFuncType(t *ast.FuncType) (Function, error) {
	f := Function{}
	if t.Params != nil {
		for _, p := range t.Params.List {
			id, ok := p.Type.(*ast.Ident)
			if !ok || !Scalar(id.Name) {
				return f, fmt.Errorf("unsupported generated runtime parameter")
			}
			n := max(1, len(p.Names))
			for range n {
				f.Params = append(f.Params, id.Name)
			}
		}
	}
	if t.Results != nil && len(t.Results.List) != 0 {
		if len(t.Results.List) != 1 {
			return f, fmt.Errorf("multiple runtime results")
		}
		id, ok := t.Results.List[0].Type.(*ast.Ident)
		if !ok || !Scalar(id.Name) {
			return f, fmt.Errorf("unsupported runtime result")
		}
		f.Result = id.Name
	}
	return f, nil
}

func emitBootstrap(out, pkg, goos, arch string) error {
	entries, err := bootstrap.ReadDir("bootstrap")
	if err != nil {
		return err
	}
	ctx := build.Default
	ctx.GOOS = goos
	ctx.GOARCH = arch
	ctx.CgoEnabled = false
	ctx.OpenFile = func(name string) (io.ReadCloser, error) { return bootstrap.Open(filepath.ToSlash(name) + ".txt") }
	rewrites := 0
	for _, entry := range entries {
		n := entry.Name()
		if !strings.HasSuffix(n, ".txt") {
			continue
		}
		original := strings.TrimSuffix(n, ".txt")
		if strings.HasPrefix(n, "LICENSE-") {
			b, _ := bootstrap.ReadFile("bootstrap/" + n)
			if err = os.WriteFile(filepath.Join(out, n), b, 0644); err != nil {
				return err
			}
			continue
		}
		match, err := ctx.MatchFile("bootstrap", original)
		if err != nil {
			return err
		}
		if !match && !strings.HasSuffix(original, ".h") {
			continue
		}
		b, err := bootstrap.ReadFile("bootstrap/" + n)
		if err != nil {
			return err
		}
		if strings.HasSuffix(original, ".go") {
			b = bytes.Replace(b, []byte("package fakecgo"), []byte("// Adapted by Bao: bootstrap shares the generated package; original notices retained.\npackage "+pkg), 1)
		}
		// The bootstrap also serves cgo-enabled builds: bao_cgo_init_thunk
		// installs its hooks only when runtime/cgo is absent.
		b = bytes.ReplaceAll(b, []byte("//go:build !cgo && "), []byte("//go:build "))
		b = bytes.ReplaceAll(b, []byte("//go:build !cgo\n"), nil)
		var count int
		b, count = rewriteBootstrapHooks(b)
		rewrites += count
		// Upstream's untagged assembly defines crosscall2, which runtime/cgo
		// also defines. Neither runtime calls it; keep the bundled copy for !cgo.
		if strings.HasPrefix(original, "asm_") && strings.HasSuffix(original, ".s") {
			b = append([]byte("//go:build !cgo\n\n"), b...)
		}
		name := "bao_bootstrap_" + original
		if strings.HasSuffix(original, ".h") {
			name = original
		}
		if err = os.WriteFile(filepath.Join(out, name), b, 0644); err != nil {
			return err
		}
	}
	if want := expectedHookRewrites(goos); rewrites != want {
		return fmt.Errorf("bootstrap hooks: rewrote %d static runtime hook definitions, want %d", rewrites, want)
	}
	if err = os.WriteFile(filepath.Join(out, "bao_bootstrap_hooks.go"), []byte(hookGo(goos, pkg)), 0644); err != nil {
		return err
	}
	asm, err := hookAssembly(goos, arch)
	if err != nil {
		return err
	}
	if err = os.WriteFile(filepath.Join(out, "bao_bootstrap_hooks_"+goos+"_"+arch+".s"), []byte(asm), 0644); err != nil {
		return err
	}
	b, _ := bootstrap.ReadFile("bootstrap/provenance.json")
	if err = os.WriteFile(filepath.Join(out, "bao-bootstrap-provenance.json"), b, 0644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(out, "NOTICE-BAO-BOOTSTRAP.txt"), []byte("This package includes adapted runtime bootstrap sources from github.com/ebitengine/purego v0.11.3/internal/fakecgo.\nOriginal Ebitengine Apache-2.0 and Go Authors BSD notices are retained in each source file.\nApache terms are in LICENSE-PUREGO.txt. Go-derived source notices refer to LICENSE-GO.txt.\nBao changes: package declaration renamed so the bootstrap is bundled in this generated package; !cgo build constraints removed; static runtime hook definitions replaced by declarations; crosscall2 assembly kept only when cgo is disabled.\nFixed-signature call adapters and the bao_bootstrap_hooks sources are authored by Bao under Apache-2.0.\nWhen runtime/cgo is not linked, this bootstrap installs process-wide Go runtime hooks from runtime._cgo_init; when it is linked, runtime/cgo provides them. Use one bundled bootstrap per executable and do not combine it with purego bootstrap providers.\n"), 0644)
}
