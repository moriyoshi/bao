package bindings

import (
	"fmt"
	"regexp"
	"strings"
)

// The bundled bootstrap originally initializes the runtime's cgo hooks
// statically, which collides with runtime/cgo when an application also links a
// cgo package. Instead, Bao owns runtime._cgo_init through a larger DUPOK slot.
// The runtime calls it once from rt0_go, before any other thread exists; the
// thunk then defers to runtime/cgo when runtime/cgo initialized runtime.iscgo,
// or installs the bundled hooks and enters the bundled x_cgo_init. One
// generated package therefore serves cgo-disabled builds, cgo-enabled builds
// without runtime/cgo, and builds that link runtime/cgo.

// Runtime hooks the thunk installs when runtime/cgo is absent. The runtime
// pushes these names, so Bao may reference them.
type hookInstall struct {
	slot  string // runtime variable written by the thunk
	value string // symbol whose address (or, with load, contents) is written
	load  bool
}

var bootstrapHooks = []hookInstall{
	{slot: "_cgo_thread_start", value: "x_cgo_thread_start_trampoline"},
	{slot: "_cgo_notify_runtime_init_done", value: "x_cgo_notify_runtime_init_done_trampoline"},
	{slot: "_cgo_pthread_key_created", value: "·x_cgo_pthread_key_created"},
	{slot: "_cgo_bindm", value: "x_cgo_bindm_trampoline"},
	{slot: "runtime·set_crosscall2", value: "·bao_set_crosscall2", load: true},
	{slot: "runtime·_cgo_setenv", value: "x_cgo_setenv_trampoline"},
	{slot: "runtime·_cgo_unsetenv", value: "x_cgo_unsetenv_trampoline"},
}

// Linux syscall hooks. syscall does not push these names, so only their
// defining package may reference them. Bao defines each as a DUPOK slot
// holding the bundled trampoline, and the thunk restores runtime/cgo's C
// function when runtime/cgo is linked.
var syscallHooks = []string{"setegid", "seteuid", "setgid", "setregid", "setresgid", "setresuid", "setreuid", "setuid", "setgroups"}

// Static hook definitions in the upstream sources and their replacements.
// Linknamed declarations of runtime hooks remain so every slot exists in
// either link.
var (
	hookAddressDef      = regexp.MustCompile(`(?m)^var (_cgo_\w+) = &\w+$`)
	syscallHookLinkname = regexp.MustCompile(`(?m)^//go:linkname _cgo_libc_\w+ syscall\.cgo_libc_\w+\n`)
	syscallHookDef      = regexp.MustCompile(`(?m)^var _cgo_libc_\w+ = &\w+\n`)
	hookFixedDefs       = []struct{ old, new string }{
		{"var _set_crosscall2 = set_crosscall2", "var _set_crosscall2 func() // installed by bao_cgo_init_thunk"},
		{"var _iscgo bool = true", "var _iscgo bool // set by bao_cgo_init_thunk"},
	}
)

// rewriteBootstrapHooks converts upstream static hook definitions into plain
// declarations and returns how many it converted. syscall's hooks are removed
// because the hook assembly defines them.
func rewriteBootstrapHooks(b []byte) ([]byte, int) {
	b = syscallHookLinkname.ReplaceAll(b, nil)
	n := len(syscallHookDef.FindAll(b, -1))
	b = syscallHookDef.ReplaceAll(b, nil)
	n += len(hookAddressDef.FindAll(b, -1))
	b = hookAddressDef.ReplaceAll(b, []byte("var $1 *byte // installed by bao_cgo_init_thunk"))
	for _, r := range hookFixedDefs {
		n += strings.Count(string(b), r.old)
		b = []byte(strings.ReplaceAll(string(b), r.old, r.new))
	}
	return b, n
}

// expectedHookRewrites is the number of upstream static definitions: the
// installed hooks plus _cgo_init and runtime.iscgo, and syscall's on Linux.
func expectedHookRewrites(goos string) int {
	n := len(bootstrapHooks) + 2
	if goos == "linux" {
		n += len(syscallHooks)
	}
	return n
}

const hookGoSource = `// Code generated by Bao; DO NOT EDIT.
// Authored by Bao under Apache-2.0.

//go:build darwin || linux

package %s

import _ "unsafe"

// runtime/cgo's C x_cgo_init when runtime/cgo is linked. Otherwise this unused
// placeholder keeps the hook thunk's reference resolvable.
//
//go:linkname bao_runtime_cgo_init x_cgo_init
var bao_runtime_cgo_init byte

// Statically initialized function value installed as runtime.set_crosscall2.
var bao_set_crosscall2 = set_crosscall2
`

// Placeholders for runtime/cgo's C syscall helpers, which the Linux thunk
// restores when runtime/cgo is linked.
const hookLinuxGoSource = `
//go:linkname bao_runtime_cgo_libc_%[1]s _cgo_libc_%[1]s
var bao_runtime_cgo_libc_%[1]s byte
`

func hookGo(goos, pkg string) string {
	s := fmt.Sprintf(hookGoSource, pkg)
	if goos == "linux" {
		for _, id := range syscallHooks {
			s += fmt.Sprintf(hookLinuxGoSource, id)
		}
	}
	return s
}

type hookArch struct {
	addr, load, store string // instruction formats moving a value through the scratch register
	test              string // branch to install when runtime.iscgo is false
	forward           string // enter runtime/cgo's x_cgo_init
	tail              string // set runtime.iscgo and enter the bundled x_cgo_init
}

// Scratch registers are caller-saved in the C ABI and leave rt0_go's
// _cgo_init arguments intact.
var hookArches = map[string]hookArch{
	"arm64": {
		addr: "MOVD\t$%s(SB), R9", load: "MOVD\t%s(SB), R9", store: "MOVD\tR9, %s(SB)",
		test:    "\tMOVBU\truntime·iscgo(SB), R9\n\tCBZ\tR9, install\n",
		forward: "\tMOVD\t$x_cgo_init(SB), R9\n\tJMP\t(R9)\n",
		tail:    "\tMOVD\t$1, R9\n\tMOVB\tR9, runtime·iscgo(SB)\n\tJMP\tx_cgo_init_trampoline(SB)\n",
	},
	"amd64": {
		addr: "LEAQ\t%s(SB), R11", load: "MOVQ\t%s(SB), R11", store: "MOVQ\tR11, %s(SB)",
		test:    "\tCMPB\truntime·iscgo(SB), $0\n\tJEQ\tinstall\n",
		forward: "\tLEAQ\tx_cgo_init(SB), R11\n\tJMP\tR11\n",
		tail:    "\tMOVB\t$1, runtime·iscgo(SB)\n\tJMP\tx_cgo_init_trampoline(SB)\n",
	},
	"loong64": {
		addr: "MOVV\t$%s(SB), R12", load: "MOVV\t%s(SB), R12", store: "MOVV\tR12, %s(SB)",
		test:    "\tMOVBU\truntime·iscgo(SB), R12\n\tBEQ\tR12, install\n",
		forward: "\tMOVV\t$x_cgo_init(SB), R12\n\tJMP\t(R12)\n",
		tail:    "\tMOVV\t$1, R12\n\tMOVB\tR12, runtime·iscgo(SB)\n\tJMP\tx_cgo_init_trampoline(SB)\n",
	},
	// rt0_go on ppc64x calls save_g before _cgo_init, while iscgo is still
	// false. Save g0 to TLS once iscgo is set, matching a statically set iscgo
	// until the runtime's next save_g. save_g clobbers only R31; LR is kept in
	// R11. C callees expect R12 to hold their entry.
	"ppc64le": {
		addr: "MOVD\t$%s(SB), R11", load: "MOVD\t%s(SB), R11", store: "MOVD\tR11, %s(SB)",
		test:    "\tMOVBZ\truntime·iscgo(SB), R11\n\tCMP\tR11, $0\n\tBEQ\tinstall\n",
		forward: "\tMOVD\t$x_cgo_init(SB), R12\n\tMOVD\tR12, CTR\n\tJMP\t(CTR)\n",
		tail:    "\tMOVD\t$1, R11\n\tMOVB\tR11, runtime·iscgo(SB)\n\tMOVD\tLR, R11\n\tBL\truntime·save_g(SB)\n\tMOVD\tR11, LR\n\tMOVD\t$x_cgo_init_trampoline(SB), R12\n\tMOVD\tR12, CTR\n\tJMP\t(CTR)\n",
	},
}

func hookAssembly(goos, arch string) (string, error) {
	a, ok := hookArches[arch]
	if !ok {
		return "", fmt.Errorf("bootstrap hooks: unsupported architecture %s", arch)
	}
	move := func(s *strings.Builder, format, value, slot string) {
		fmt.Fprintf(s, "\t"+format+"\n\t"+a.store+"\n", value, slot)
	}
	var s strings.Builder
	fmt.Fprintf(&s, `// Code generated by Bao; DO NOT EDIT.
// Authored by Bao under Apache-2.0.

//go:build %s

#include "textflag.h"

// The runtime reads _cgo_init in rt0_go, before Go initialization, and calls
// it with the C ABI. These 16-byte DUPOK definitions take precedence over the
// 8-byte runtime placeholders and runtime/cgo pointers in either load order.
DATA	_cgo_init+0(SB)/8, $bao_cgo_init_thunk(SB)
DATA	_cgo_init+8(SB)/8, $0
GLOBL	_cgo_init(SB), DUPOK|NOPTR, $16
`, goos)
	if goos == "linux" {
		for _, id := range syscallHooks {
			fmt.Fprintf(&s, "\nDATA\tsyscall·cgo_libc_%[1]s+0(SB)/8, $_cgo_purego_%[1]s_trampoline(SB)\nDATA\tsyscall·cgo_libc_%[1]s+8(SB)/8, $0\nGLOBL\tsyscall·cgo_libc_%[1]s(SB), DUPOK|NOPTR, $16\n", id)
		}
	}
	s.WriteString(`
// runtime/cgo initializes runtime.iscgo statically. If it is set, defer to
// runtime/cgo's x_cgo_init. Otherwise install the bundled hooks, set iscgo and
// enter the bundled x_cgo_init with the original arguments.
TEXT bao_cgo_init_thunk(SB), NOSPLIT|NOFRAME, $0-0
`)
	s.WriteString(a.test)
	if goos == "linux" {
		for _, id := range syscallHooks {
			move(&s, a.addr, "_cgo_libc_"+id, "syscall·cgo_libc_"+id)
		}
	}
	s.WriteString(a.forward)
	s.WriteString("install:\n")
	for _, h := range bootstrapHooks {
		format := a.addr
		if h.load {
			format = a.load
		}
		move(&s, format, h.value, h.slot)
	}
	s.WriteString(a.tail)
	return s.String(), nil
}
