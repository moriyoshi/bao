package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/moriyoshi/bao/linuxelf"
)

func translateELF(args []string, stderr io.Writer) error {
	fs := flag.NewFlagSet("translate-elf", flag.ContinueOnError)
	fs.SetOutput(stderr)
	out := fs.String("o", "", "new generated Go package directory")
	pkg := fs.String("package", "native", "Go package name")
	sysroot := fs.String("sysroot", "", "Linux target glibc sysroot (ELF shared libraries)")
	var symbols symbolFlags
	fs.Var(&symbols, "symbol", "native external symbol, repeatable")
	var systemLibraries symbolFlags
	fs.Var(&systemLibraries, "linux-system-library", "additional target shared object in -sysroot, such as libxcb.so.1; repeatable")
	if err := parseFlags(fs, args, stderr); err != nil {
		return err
	}
	if fs.NArg() != 1 || *out == "" {
		return fmt.Errorf("usage: bao translate-elf -sysroot target-root -o new-directory [-symbol native_fn] combined.o")
	}
	if !token.IsIdentifier(*pkg) || *pkg == "_" {
		return fmt.Errorf("invalid Go package name")
	}
	for _, s := range symbols {
		if !token.IsIdentifier(s) || s == "_" {
			return fmt.Errorf("invalid export name %q", s)
		}
	}
	input, err := os.ReadFile(fs.Arg(0))
	if err != nil {
		return err
	}
	p, err := linuxelf.TranslateWithOptions(input, *sysroot, symbols, linuxelf.Options{SystemLibraries: systemLibraries})
	if err != nil {
		return err
	}
	var goSrc, asm strings.Builder
	fmt.Fprintf(&goSrc, "// Code generated by bao; DO NOT EDIT.\n//go:build linux && %s\n\npackage %s\n\nimport (\n\"github.com/ebitengine/purego\"\n\"os\"\n\"runtime\"\n\"sync\"\n\"unsafe\"\n)\n", p.Arch, *pkg)
	asm.WriteString("// Code generated by bao; DO NOT EDIT.\n#include \"textflag.h\"\n")
	move, reg := "MOVD", "R0"
	if p.Arch == "amd64" {
		move, reg = "MOVQ", "AX"
	}
	if p.Arch == "loong64" {
		move, reg = "MOVV", "R4"
	}
	if p.Arch == "ppc64le" {
		reg = "R3"
	}
	accessor := func(local, native string) {
		fmt.Fprintf(&goSrc, "\nfunc %s() uintptr\n", local)
		fmt.Fprintf(&asm, "\nTEXT ·%s(SB),NOSPLIT,$0-8\n\t%s $%s(SB), %s\n\t%s %s, ret+0(FP)\n\tRET\n", local, move, native, reg, move, reg)
	}
	for i, s := range symbols {
		accessor(fmt.Sprintf("SymbolAddr%d", i), s)
	}
	for _, b := range p.Imports {
		fmt.Fprintf(&goSrc, "\n//go:cgo_import_dynamic %s %s %q\n", b.Local, b.Remote, b.Library)
	}
	if p.RegisterFrame == "" {
		goSrc.WriteString("\n//go:cgo_import_dynamic _ _ \"libgcc_s.so.1\"\n")
	} else {
		accessor("registerFrameAddress", p.RegisterFrame)
	}
	accessor("templateAddress", p.TLSTemplateSymbol)
	for _, name := range []string{"tls_configure", "tls_patch_pointer", "tls_live_blocks", "tls_destroyed_blocks", "tls_finalize_current_thread", "runtime_allocate_args", "runtime_set_arg", "runtime_call_constructor", "runtime_read_pointer"} {
		accessor("address_"+name, p.Runtime(name))
	}
	for i, f := range p.LocalFixups {
		accessor(fmt.Sprintf("localPlace%d", i), f.Location)
		accessor(fmt.Sprintf("localTarget%d", i), f.Target)
		accessor(fmt.Sprintf("localSubtract%d", i), f.Subtract)
	}
	if len(p.LocalFixups) != 0 {
		accessor("address_runtime_patch_u32", p.Runtime("runtime_patch_u32"))
	}
	for i, f := range p.Fixups {
		accessor(fmt.Sprintf("fixupAddress%d", i), f.Location)
	}
	for i, s := range p.Unwind {
		accessor(fmt.Sprintf("unwindAddress%d", i), s)
	}
	for i, s := range p.Constructors {
		accessor(fmt.Sprintf("constructorsAddress%d", i), s.Symbol)
	}
	for i, s := range p.Finalizers {
		accessor(fmt.Sprintf("finalizersAddress%d", i), s.Symbol)
	}
	goSrc.WriteString("\n// FinalizeRuntime runs native fini arrays once. Stop native work, finalize caller TLS and C++ objects before calling.\nvar finalizersOnce sync.Once\nfunc FinalizeRuntime() { finalizersOnce.Do(func() {\n")
	if len(p.Finalizers) != 0 {
		goSrc.WriteString("var readPointer func(uintptr) uintptr\npurego.RegisterFunc(&readPointer, address_runtime_read_pointer())\n")
		for i, table := range p.Finalizers {
			fmt.Fprintf(&goSrc, "for i := %d; i >= 0; i-- { var finalize func(); purego.RegisterFunc(&finalize, readPointer(finalizersAddress%d()+uintptr(i)*8)); finalize() }\n", table.Count-1, i)
		}
	}
	goSrc.WriteString("}) }\n")
	goSrc.WriteString(`
var tlsLive func() uint64
var tlsDestroyed func() uint64
var tlsFinalize func()

func lookup(name string) uintptr {
    address, err := purego.Dlsym(purego.RTLD_DEFAULT, name)
    if err != nil { panic(err) }; return address
}

// TLSLiveBlocks counts this image's allocated native per-thread blocks.
func TLSLiveBlocks() uint64 { return tlsLive() }
// TLSDestroyedBlocks counts blocks released after native TLS destructors.
func TLSDestroyedBlocks() uint64 { return tlsDestroyed() }
// TLSFinalizeCurrentThread must run on the locked OS thread after native teardown,
// with no remaining references to its TLS. Native pthread exits finalize automatically.
func TLSFinalizeCurrentThread() { tlsFinalize() }

func init() {
    runtime.LockOSThread()
    defer runtime.UnlockOSThread()
    var configure func(uintptr, uintptr, uintptr) int32
    purego.RegisterFunc(&configure, address_tls_configure())
`)
	fmt.Fprintf(&goSrc, "    if status := configure(templateAddress(), %d, %d); status != 0 { panic(status) }\n", p.TLSTemplateSize, p.TLSTemplateAlignment)
	goSrc.WriteString(`    purego.RegisterFunc(&tlsLive, address_tls_live_blocks())
    purego.RegisterFunc(&tlsDestroyed, address_tls_destroyed_blocks())
    purego.RegisterFunc(&tlsFinalize, address_tls_finalize_current_thread())
`)
	if len(p.Fixups) != 0 {
		goSrc.WriteString("    var patch func(uintptr, uintptr)\n    purego.RegisterFunc(&patch, address_tls_patch_pointer())\n")
		for i, f := range p.Fixups {
			remote := ""
			for _, b := range p.Imports {
				if b.Local == f.Import {
					remote = b.Remote
					break
				}
			}
			fmt.Fprintf(&goSrc, "    patch(fixupAddress%d(), lookup(%q)+uintptr(%d))\n", i, remote, uint64(f.Addend))
		}
	}
	if len(p.LocalFixups) != 0 {
		word, u32 := false, false
		for _, f := range p.LocalFixups {
			word = word || f.Width == 8
			u32 = u32 || f.Width == 4
		}
		if word {
			goSrc.WriteString("    var patchWord func(uintptr, uintptr)\n    purego.RegisterFunc(&patchWord, address_tls_patch_pointer())\n")
		}
		if u32 {
			goSrc.WriteString("    var patchU32 func(uintptr, uint32)\n    purego.RegisterFunc(&patchU32, address_runtime_patch_u32())\n")
		}
		for i, f := range p.LocalFixups {
			fmt.Fprintf(&goSrc, "    { value := int64(localTarget%d())-int64(localSubtract%d())+int64(%d)\n", i, i, f.Addend)
			if f.Width == 4 {
				goSrc.WriteString("    if int64(int32(value))!=value { panic(\"native relative data overflow\") }\n")
				fmt.Fprintf(&goSrc, "    patchU32(localPlace%d(),uint32(value)) }\n", i)
			} else {
				fmt.Fprintf(&goSrc, "    patchWord(localPlace%d(),uintptr(value)) }\n", i)
			}
		}
	}
	if len(p.Unwind) != 0 {
		goSrc.WriteString("    var registerFrame func(uintptr)\n")
		if p.RegisterFrame != "" {
			goSrc.WriteString("    purego.RegisterFunc(&registerFrame, registerFrameAddress())\n")
		} else {
			goSrc.WriteString("    purego.RegisterFunc(&registerFrame, lookup(\"__register_frame\"))\n")
		}
		for i := range p.Unwind {
			fmt.Fprintf(&goSrc, "    registerFrame(unwindAddress%d())\n", i)
		}
	}
	goSrc.WriteString(`    var allocateArgs func(int32) int32
    var setArg func(int32, uintptr) int32
    purego.RegisterFunc(&allocateArgs, address_runtime_allocate_args())
    purego.RegisterFunc(&setArg, address_runtime_set_arg())
    if allocateArgs(int32(len(os.Args))) != 0 { panic("native argv allocation") }
    for i, arg := range os.Args {
        value := append([]byte(arg), 0)
        status := setArg(int32(i), uintptr(unsafe.Pointer(&value[0])))
        runtime.KeepAlive(value)
        if status != 0 { panic("native argv copy") }
    }
`)
	if len(p.Constructors) != 0 {
		goSrc.WriteString("    var readPointer func(uintptr) uintptr\n    var callConstructor func(uintptr)\n    purego.RegisterFunc(&readPointer, address_runtime_read_pointer())\n    purego.RegisterFunc(&callConstructor, address_runtime_call_constructor())\n")
		for i, t := range p.Constructors {
			fmt.Fprintf(&goSrc, "    for off := uintptr(0); off < %d; off += 8 {\n        fn := readPointer(constructorsAddress%d()+off)\n        if fn == 0 { panic(\"null native initializer\") }; callConstructor(fn)\n    }\n", t.Count*8, i)
		}
	}
	goSrc.WriteString("}\n")
	formatted, err := format.Source([]byte(goSrc.String()))
	if err != nil {
		return err
	}
	manifest, err := json.MarshalIndent(p, "", "  ")
	if err != nil {
		return err
	}
	if err := os.Mkdir(*out, 0755); err != nil {
		return err
	}
	complete := false
	defer func() {
		if !complete {
			os.RemoveAll(*out)
		}
	}()
	for i, b := range p.Objects {
		if err := writeNew(filepath.Join(*out, fmt.Sprintf("native_%d_linux_%s.syso", i, p.Arch)), b); err != nil {
			return err
		}
	}
	for name, b := range map[string][]byte{"symbols_linux_" + p.Arch + ".go": formatted, "symbols_linux_" + p.Arch + ".s": []byte(asm.String()), "bao-manifest.json": append(manifest, '\n')} {
		if err := writeNew(filepath.Join(*out, name), b); err != nil {
			return err
		}
	}
	complete = true
	fmt.Fprintf(stderr, "translated Linux %s ELF image: %d TLS descriptors, %d import bindings, %d initializer tables; verify target execution separately\n", p.Arch, p.TLSDescriptors, len(p.Imports), len(p.Constructors))
	return nil
}
